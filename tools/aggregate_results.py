#!/usr/bin/env python3
"""Aggregate per-method JSONL benchmark results into Markdown, JSON, CSV, and LaTeX.

Reads ``<results-dir>/*.jsonl`` alongside ``<dataset>/manifest.json``, computes
all three evaluation pillars via :func:`astverifier.shared.metrics.aggregate`,
prints a Markdown comparison table, and writes:

* ``<results-dir>/summary.json``
* ``<results-dir>/summary.csv``
* ``<results-dir>/table_benchmark.tex``
"""

from __future__ import annotations

import argparse
import csv
import json
import sys
from dataclasses import asdict
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
SRC_DIR = ROOT / "src"
if str(SRC_DIR) not in sys.path:
    sys.path.insert(0, str(SRC_DIR))

from astverifier.baselines import EXPECTED_IDS, get_baseline  # noqa: E402
from astverifier.shared.claims import load_ground_truth  # noqa: E402
from astverifier.shared.metrics import (  # noqa: E402
    Metrics,
    aggregate,
    resolve_pricing,
)
from astverifier.shared.schemas import ProgramResult  # noqa: E402

METHOD_ORDER: tuple[str, ...] = (
    "PROPOSED",
    "PROPOSED_NO_INV",
    "PROPOSED_NO_REPLAY",
    "PROPOSED_LLM",
    *EXPECTED_IDS,
)

PROPOSED_LABELS: dict[str, str] = {
    "PROPOSED": "Proposed (AST-Anchored + Houdini + Replay)",
    "PROPOSED_NO_INV": "Ablation: Proposed w/o Invariants",
    "PROPOSED_NO_REPLAY": "Ablation: Proposed w/o Replay",
    "PROPOSED_LLM": "Proposed + LLM CoT & Feedback",
}


def method_display_name(method_id: str) -> str:
    if method_id in PROPOSED_LABELS:
        return PROPOSED_LABELS[method_id]
    try:
        cls = get_baseline(method_id)
        return f"Baseline {cls.id}: {cls.name}"
    except KeyError:
        return method_id


def load_jsonl_results(path: Path) -> list[ProgramResult]:
    """Load ``ProgramResult`` records from JSONL, deduplicating by program_id."""
    by_pid: dict[str, ProgramResult] = {}
    with path.open("r", encoding="utf-8") as fh:
        for line_no, raw in enumerate(fh, 1):
            line = raw.strip()
            if not line:
                continue
            try:
                res = ProgramResult.model_validate_json(line)
                by_pid[res.program_id] = res
            except Exception as exc:  # noqa: BLE001
                print(
                    f"[warn] Skipping invalid line {line_no} in {path.name}: {exc}",
                    file=sys.stderr,
                )
    return list(by_pid.values())


def load_meta(results_dir: Path, method_id: str) -> dict[str, Any]:
    meta_path = results_dir / f"{method_id}.meta.json"
    if not meta_path.exists():
        return {}
    try:
        return json.loads(meta_path.read_text(encoding="utf-8"))
    except json.JSONDecodeError:
        return {}


def _fmt_pct(val: float | None) -> str:
    return "N/A" if val is None else f"{val * 100.0:.2f}%"


def _fmt_pct_tex(val: float | None) -> str:
    return "N/A" if val is None else f"{val * 100.0:.2f}\\%"


def _fmt_cost(val: float) -> str:
    return "$0.0000" if val == 0 else f"${val:.4f}"


def _sort_key(method_id: str) -> tuple[int, str]:
    try:
        return (METHOD_ORDER.index(method_id), method_id)
    except ValueError:
        return (len(METHOD_ORDER), method_id)


def render_markdown(rows: list[dict[str, Any]]) -> str:
    header = (
        "| Method | N | Acc | Prec | Rec | F1 | FDR | V | CE | UNR | UNK | "
        "HR | CRVR | Tok In/p | Tok Out/p | Total ($) | Avg Lat (s) |"
    )
    sep = (
        "| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | "
        "---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |"
    )
    lines = [header, sep]
    for row in rows:
        m: Metrics = row["metrics"]
        lines.append(
            f"| `{row['method']}` | {m.n_programs} | "
            f"{_fmt_pct(m.accuracy)} | {_fmt_pct(m.precision)} | "
            f"{_fmt_pct(m.recall)} | {_fmt_pct(m.f1)} | {_fmt_pct(m.fdr)} | "
            f"{m.n_verified} | {m.n_counterexample} | {m.n_unreachable} | "
            f"{m.n_unknown_timeout} | {_fmt_pct(m.hr)} | {_fmt_pct(m.crvr)} | "
            f"{m.token_avg_in:.1f} | {m.token_avg_out:.1f} | "
            f"{_fmt_cost(m.total_cost_usd)} | {m.latency_avg_s:.3f} |"
        )
    return "\n".join(lines)


def _tex_escape(text: str) -> str:
    return (
        text.replace("\\", "\\textbackslash{}")
        .replace("_", "\\_")
        .replace("&", "\\&")
        .replace("%", "\\%")
    )


def render_latex(rows: list[dict[str, Any]]) -> str:
    lines = [
        "% Auto-generated by tools/aggregate_results.py",
        "\\begin{table}[htbp]",
        "\\centering",
        "\\small",
        "\\caption{So sánh kết quả thực nghiệm trên bộ dữ liệu chuẩn.}",
        "\\label{tab:benchmark-results}",
        "\\begin{tabular}{lrrrrrrrrrr}",
        "\\toprule",
        "Phương pháp & $N$ & Acc & F1 & FDR & V & CE & UNK & HR & CRVR & Lat (s) \\\\",
        "\\midrule",
    ]
    for row in rows:
        m: Metrics = row["metrics"]
        label = _tex_escape(row["method"])
        lines.append(
            f"{label} & {m.n_programs} & "
            f"{_fmt_pct_tex(m.accuracy)} & {_fmt_pct_tex(m.f1)} & "
            f"{_fmt_pct_tex(m.fdr)} & {m.n_verified} & {m.n_counterexample} & "
            f"{m.n_unknown_timeout} & {_fmt_pct_tex(m.hr)} & "
            f"{_fmt_pct_tex(m.crvr)} & {m.latency_avg_s:.3f} \\\\"
        )
    lines.extend(
        [
            "\\bottomrule",
            "\\end{tabular}",
            "\\end{table}",
            "",
        ]
    )
    return "\n".join(lines)


def write_csv(path: Path, rows: list[dict[str, Any]]) -> None:
    fieldnames = [
        "method",
        "display_name",
        "provider",
        "model",
        "n_programs",
        "n_claims",
        "accuracy",
        "precision",
        "recall",
        "f1",
        "fdr",
        "tp",
        "fp",
        "fn",
        "tn",
        "n_verified",
        "n_counterexample",
        "n_unreachable",
        "n_unknown_timeout",
        "n_unsupported",
        "n_translation_error",
        "hr",
        "crvr",
        "crvr_confirmed",
        "crvr_total",
        "token_avg_in",
        "token_avg_out",
        "total_tokens_in",
        "total_tokens_out",
        "cost_avg_usd",
        "total_cost_usd",
        "latency_avg_s",
        "total_elapsed_s",
    ]
    with path.open("w", encoding="utf-8", newline="") as fh:
        writer = csv.DictWriter(fh, fieldnames=fieldnames)
        writer.writeheader()
        for row in rows:
            m_dict = asdict(row["metrics"])
            out_row = {
                "method": row["method"],
                "display_name": row["display_name"],
                "provider": row["provider"],
                "model": row["model"],
            }
            for key in fieldnames[4:]:
                out_row[key] = m_dict.get(key)
            writer.writerow(out_row)


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Aggregate benchmark JSONL outputs into Markdown, JSON, CSV, and LaTeX."
    )
    parser.add_argument(
        "--results-dir",
        type=Path,
        default=ROOT / "results",
        help="Directory containing <METHOD>.jsonl files.",
    )
    parser.add_argument(
        "--dataset",
        type=Path,
        default=ROOT / "dataset",
        help="Dataset directory containing manifest.json.",
    )
    parser.add_argument(
        "--methods",
        type=str,
        default="",
        help="Optional comma-separated subset of method IDs to include.",
    )
    parser.add_argument(
        "--price-in-1m",
        type=float,
        default=None,
        help="Override input token price (USD per 1M tokens) for all methods.",
    )
    parser.add_argument(
        "--price-out-1m",
        type=float,
        default=None,
        help="Override output token price (USD per 1M tokens) for all methods.",
    )
    return parser


def main(argv: list[str] | None = None) -> int:
    parser = build_parser()
    args = parser.parse_args(argv)

    results_dir = args.results_dir.resolve()
    manifest_path = args.dataset.resolve() / "manifest.json"
    if not manifest_path.exists():
        raise FileNotFoundError(f"Manifest not found: {manifest_path}")
    ground_truth = load_ground_truth(manifest_path)

    if args.methods.strip():
        method_ids = [m.strip().upper() for m in args.methods.split(",") if m.strip()]
    else:
        method_ids = sorted(
            (p.stem for p in results_dir.glob("*.jsonl")),
            key=_sort_key,
        )

    if not method_ids:
        print(f"No .jsonl result files found in {results_dir}", file=sys.stderr)
        return 1

    rows: list[dict[str, Any]] = []
    for method_id in method_ids:
        jsonl_path = results_dir / f"{method_id}.jsonl"
        if not jsonl_path.exists():
            print(f"[warn] Missing {jsonl_path}, skipping.", file=sys.stderr)
            continue
        results = load_jsonl_results(jsonl_path)
        meta = load_meta(results_dir, method_id)
        provider = str(
            meta.get(
                "provider",
                "offline"
                if method_id
                in ("PROPOSED", "PROPOSED_NO_INV", "PROPOSED_NO_REPLAY", "J", "K", "L")
                else "unknown",
            )
        )
        model = str(meta.get("model", "offline" if provider == "offline" else "unknown"))

        if args.price_in_1m is not None and args.price_out_1m is not None:
            p_in, p_out = args.price_in_1m, args.price_out_1m
        else:
            p_in, p_out = resolve_pricing(model, provider=provider)

        metrics = aggregate(
            results,
            ground_truth,
            price_in_per_1m=p_in,
            price_out_per_1m=p_out,
        )
        rows.append(
            {
                "method": method_id,
                "display_name": method_display_name(method_id),
                "provider": provider,
                "model": model,
                "price_in_per_1m": p_in,
                "price_out_per_1m": p_out,
                "metrics": metrics,
            }
        )

    if not rows:
        print("No valid method results to aggregate.", file=sys.stderr)
        return 1

    md_table = render_markdown(rows)
    print(md_table)

    summary_json = {
        "dataset": str(args.dataset),
        "n_ground_truth": len(ground_truth),
        "methods": [
            {
                "method": r["method"],
                "display_name": r["display_name"],
                "provider": r["provider"],
                "model": r["model"],
                "price_in_per_1m": r["price_in_per_1m"],
                "price_out_per_1m": r["price_out_per_1m"],
                "metrics": asdict(r["metrics"]),
            }
            for r in rows
        ],
    }
    (results_dir / "summary.json").write_text(
        json.dumps(summary_json, indent=2) + "\n", encoding="utf-8"
    )
    write_csv(results_dir / "summary.csv", rows)
    (results_dir / "table_benchmark.tex").write_text(
        render_latex(rows), encoding="utf-8"
    )

    print(
        f"\nWrote:\n"
        f"  - {results_dir / 'summary.json'}\n"
        f"  - {results_dir / 'summary.csv'}\n"
        f"  - {results_dir / 'table_benchmark.tex'}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
